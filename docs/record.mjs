import { chromium } from '@playwright/test';
const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1100},recordVideo:{dir:'media/raw',size:{width:1440,height:1100}}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:5173');
await page.waitForTimeout(2000);
await page.getByRole('button',{name:'Atualizar pedidos'}).click();
await page.getByRole('table').waitFor();
await page.waitForTimeout(3000);
await page.getByLabel('Cenário').selectOption('error');
await page.getByRole('button',{name:'Atualizar pedidos'}).click();
await page.getByRole('alert').waitFor();
await page.screenshot({path:'media/desktop.png',fullPage:true});
await page.waitForTimeout(5000);
await page.getByLabel('Cenário').selectOption('success');
await page.getByRole('button',{name:'Tentar novamente'}).click();
await page.getByRole('alert').waitFor({state:'hidden'});
await page.waitForTimeout(4000);
await context.close();
const mobile=await browser.newPage({viewport:{width:390,height:844}});
await mobile.goto('http://127.0.0.1:5173'); await mobile.getByRole('button',{name:'Atualizar pedidos'}).click(); await mobile.getByRole('table').waitFor(); await mobile.screenshot({path:'media/mobile.png',fullPage:true});
await browser.close();
